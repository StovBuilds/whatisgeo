import { sections, site, updated } from '../data/content';
import { questions, sources } from '../lib/content';
import { guides, guidesIn, categoriesWithGuides } from '../lib/guides';
// llms.txt per https://llmstxt.org/: H1, one-line blockquote summary, short context,
// then H2 sections of "- [name](url): notes" links. Generated from the same data as the
// visible guide so it cannot drift from the page.
const chapters = sections.filter(s => s.id !== 'hero' && s.id !== 'updates');
// First sentence, or as many as it takes to reach ~40 characters so a terse "No." answer still says something.
const firstSentence = (text: string) => { const parts = text.replace(/\s+/g, ' ').trim().split(/(?<=[.!?])\s/); let out = ''; for (const p of parts) { out = out ? `${out} ${p}` : p; if (out.length >= 40) break; } return out; };
const chapterNote = (s: { id: string; markdown: string }) => s.id === 'questions' ? 'Ten plain answers about GEO cost, timelines, guarantees, llms.txt and the training/search split.' : firstSentence(s.markdown.replace(/^###? .*$/gm, '').replace(/\|.*\|/g, ''));
// Short factual notes on each cited source, taken from how the guide itself describes it.
const sourceNotes: Record<string, string> = {
  'https://developers.google.com/search/docs/appearance/ai-features': "Google's guidance on AI features in Search, which the guide uses for the point that a page must be indexed and eligible for a search snippet to be a supporting link in AI Overviews or AI Mode.",
  'https://arxiv.org/abs/2311.09735': 'the KDD 2024 research paper that the guide cites for its finding that adding citations, quotations and statistics could improve visibility in benchmark tests, with results varying by domain and topic.',
  'https://developers.openai.com/api/docs/bots': "OpenAI's crawler documentation, which the guide uses for the split between OAI-SearchBot (search retrieval), GPTBot (training data collection) and ChatGPT-User (visits triggered by a user's request).",
  'https://docs.perplexity.ai/docs/resources/perplexity-crawlers': "Perplexity's crawler documentation, which the guide uses for the point that PerplexityBot exists to surface and link sites within answers rather than to train a foundation model.",
  'https://llmstxt.org/': 'the proposal for an optional llms.txt file, which the guide describes as experimental and not a proven ranking factor.',
};

export function GET() {
  const body = `# ${site.name}

> ${site.description}

Published by ${site.publisher.name} (${site.publisher.url}). Registered in England and Wales, company no. 10047328, registered office 5 Brayford Square, London E1 0SG. VAT GB362654684. Contact: ${site.contact}. Last reviewed ${updated}.

GEO (Generative Engine Optimisation) is the practice of improving how visible and accurately represented a website is in answers generated by AI systems such as ChatGPT, Google's AI Overviews and Perplexity. GEO sits on top of SEO rather than replacing it; it influences the odds of being cited and guarantees nothing. This site is a free educational guide written for business owners and marketers: one long guide on the home page, plus shorter guides that each answer one question. It has no product to sell. This file is a navigation aid, not a statement of ranking eligibility or crawl permission.

## Guide

- [Complete guide, Markdown](${site.url}/guide.md): The whole guide as one Markdown document, with source links.
- [Complete guide, plain text](${site.url}/llms-full.txt): The same guide as plain text.
${chapters.map(s => `- [${s.title}](${site.url}/#${s.id}): ${chapterNote(s)}`).join('\n')}

${guides.length ? `## Guides, one question each

- [All guides](${site.url}/guides/): Index of every guide, grouped by topic. Each guide also has a Markdown version at the same path with .md.
${categoriesWithGuides().map(c => guidesIn(c.id).map(g => `- [${g.fm.title}](${site.url}${g.url}): ${g.fm.summary} Markdown: ${site.url}${g.md}`).join('\n')).join('\n')}

` : ''}## Common questions

${questions().map(q => `- [${q.question}](${site.url}/#questions): ${firstSentence(q.answer)}`).join('\n')}

## Sources the guide cites

${sources.map(s => `- [${s.name}](${s.url})${sourceNotes[s.url] ? `: ${sourceNotes[s.url]}` : ''}`).join('\n')}

## Publisher

- [Adapt Progress Evolve Limited](${site.publisher.url}): The UK software studio that publishes this guide. Registered in England and Wales, company no. 10047328, registered office 5 Brayford Square, London E1 0SG. VAT GB362654684.
- [Adapt Progress Evolve Limited on hilyt](${site.publisher.hilyt}): AI-readable profile of the publisher.
- [What is GEO on hilyt](${site.hilyt}): AI-readable profile of this site.
- [Source code](${site.source}): The site's code on GitHub (MIT); the guide text itself is © the publisher.

## Optional

- [Privacy](${site.url}/privacy/): Newsletter data and website preferences.
- [Sitemap](${site.url}/sitemap.xml): XML sitemap listing the home page, the guides index, every guide and the privacy page, with last-modified dates.
`;
  return new Response(body, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
}
